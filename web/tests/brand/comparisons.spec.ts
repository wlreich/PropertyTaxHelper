import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('comparison selection, median, manual search, release switching and responsive access',async({page},info)=>{
 await page.goto('/property/100');
 await page.getByRole('navigation',{name:'Property tools'}).getByRole('link',{name:'Compare properties',exact:true}).click();
 await expect(page).toHaveURL(/\/property\/100\/compare/);
 await expect(page.getByRole('heading',{name:'Compare your assessment',exact:true})).toBeVisible();
 await expect(page.getByRole('navigation',{name:'Property tools'}).locator('[aria-current="page"]')).toHaveText('Compare properties');
 const results=page.getByRole('region',{name:'Your selected properties, side by side'});
 await expect(results).toContainText('$460,000');
 await expect(results).toContainText('$10,000 below');
 await expect(results).toContainText('2.2% lower');
 await page.getByRole('button',{name:'Clear selections',exact:true}).click();
 await expect(results).toContainText('Select properties');
 await page.getByRole('checkbox',{name:'Select 120 CYPRESS ST (120)',exact:true}).check();
 await expect(results).toContainText('$50,000 above');
 await expect(results).toContainText('12.5% higher');
 await page.reload();
 await expect(results).toContainText('$50,000 above');
 const add=page.getByRole('link',{name:'+ Add by address or ID',exact:true});
 await add.focus();await page.keyboard.press('Enter');
 await expect(page.locator('#comparison-search-heading')).toBeFocused();
 await page.getByLabel('Property address or ID',{exact:true}).fill('PINE');
 await page.getByRole('button',{name:'Search properties',exact:true}).click();
 await page.getByRole('checkbox',{name:'Select 123 PINE ST (123)',exact:true}).check();
 await expect(results).toContainText('1 with missing values left out');
 await expect(results).toContainText('$50,000 above');
 await page.getByRole('button',{name:'Remove 123 PINE ST (123)',exact:true}).click();
 await page.getByRole('link',{name:'Compare selected properties',exact:true}).focus();await page.keyboard.press('Enter');
 await expect(page.locator('#selected-comparison-heading')).toBeFocused();
 await page.getByRole('link',{name:'How the rules work',exact:true}).focus();await page.keyboard.press('Enter');
 await expect(page.locator('#comparison-rules-heading')).toBeFocused();
 await expect(page.getByText('What ParcelSavvy can check today:',{exact:true})).toBeVisible();
 await page.locator('#comparison-rules-heading').click();
 const violations=(await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations;
 expect(violations).toEqual([]);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.evaluate(()=>{document.documentElement.style.fontSize='200%';});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.evaluate(()=>{document.documentElement.style.fontSize='';window.scrollTo(0,0);});
 const capture=info.outputPath('comparison-page.png');await page.screenshot({path:capture,fullPage:true});await info.attach('Comparison page',{path:capture,contentType:'image/png'});
 await page.getByLabel('Assessment release').selectOption('22222222-2222-4222-8222-222222222222');
 await expect(results).toContainText('$30,000 above');
 await expect(results).toContainText('2025 certified');
 await expect(page.getByText('2025 rules have not been verified.',{exact:false})).toBeVisible();
 await page.goto('/property/103/compare');await expect(page.getByRole('heading',{name:"Let’s try another address"})).toBeVisible();
});
